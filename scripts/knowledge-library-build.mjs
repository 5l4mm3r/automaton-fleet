#!/usr/bin/env node
/**
 * Build the founders' foundational knowledge library (JSON, and the generated src/fleet/postgres/knowledge-library-v1.ts that
 * schema v50 seeds from) from its reviewed Markdown source.
 *
 *   node scripts/knowledge-library-build.mjs [docs/knowledge/foundational-library-v0.1.md] [data/knowledge/foundational-library-v1.json]
 *
 * Each "### <id>" section under "## Category N" becomes one entry: title, body, factsThatChange (with the confidence the
 * source states — VERIFIED / SNIPPET / SECONDARY / UNVERIFIED — and lastChecked), sources (URL + licence note), tags from
 * the retrieval-guidance list, and hardRules: the body's own non-negotiable sentences ("Never …", "Do not …", "… is a hard
 * rule", "… is unlawful / banned"). Deterministic: the same source always yields the same file.
 */
import fs from "node:fs";

const [src = "docs/knowledge/foundational-library-v0.1.md", out = "data/knowledge/foundational-library-v1.json"] = process.argv.slice(2);
const md = fs.readFileSync(src, "utf8");
const CATEGORIES = ["demand-validation", "product-formats-pricing", "sales-channels", "acquisition", "delivery-support", "uk-legal-compliance", "unit-economics", "ethics-safety"];
const LAST_CHECKED = "2026-10-08";

const tags = new Map();
for (const m of md.matchAll(/^- \*\*([a-z0-9-]+)\*\*: (.+)$/gm)) tags.set(m[1], m[2].split(",").map((t) => t.trim()).filter(Boolean));

const confidence = (t) => /UNVERIFIED/.test(t) ? "unverified" : /SECONDARY/.test(t) ? "secondary" : /SNIPPET/.test(t) ? "official-snippet" : /VERIFIED/.test(t) ? "verified-official" : "unverified";
const HARD = /^(Never|Do not|Don't|You must not|Must not)\b|hard rule|is unlawful|is banned|banned practice|prohibit|illegal|\byou must\b|is not allowed|are not allowed/i;

const entries = [];
let cat = -1;
const stop = md.indexOf("## (a) Recommended JSON schema");
const body = stop > 0 ? md.slice(0, stop) : md;
const LABEL = /^\*\*(Title|Body|Facts that change|Sources)\*\*(?: \([^)]*\))?:|^\*\*(Title|Body|Facts that change|Sources):\*\*/;
const urls = (t) => [...t.matchAll(/https?:\/\/[^\s),]+/g)].map((m) => m[0].replace(/[.;]$/, ""));
/** Non-negotiable lines of a body: a matching line, plus the bullet items it introduces when it ends with ":". */
function hardRules(text) {
  const out = [];
  const ls = text.split("\n");
  for (let i = 0; i < ls.length; i++) {
    const l = ls[i].replace(/^- /, "").trim();
    if (!HARD.test(l)) continue;
    if (l.endsWith(":")) {
      const items = [];
      for (let j = i + 1; j < ls.length && /^- /.test(ls[j]); j++) items.push(ls[j].slice(2).trim());
      out.push(`${l} ${items.join("; ")}`.slice(0, 600));
    } else out.push(l.slice(0, 600));
  }
  return out;
}
for (const block of body.split(/^(?=## Category |### )/m)) {
  const c = /^## Category (\d+)/.exec(block);
  if (c) { cat = Number(c[1]) - 1; continue; }
  const h = /^### ([a-z0-9-]+)\s*\n/.exec(block);
  if (!h || cat < 0) continue;
  const id = h[1];
  const f = { Title: [], Body: [], "Facts that change": [], Sources: [] };
  let cur = null;
  for (const line of block.split("\n").slice(1)) {
    if (/^---\s*$/.test(line)) break;
    const m = LABEL.exec(line);
    if (m) { cur = m[1] ?? m[2]; f[cur].push(line.slice(m[0].length)); continue; }
    if (cur) f[cur].push(line);
  }
  const t = (k) => f[k].join("\n").trim();
  const facts = t("Facts that change");
  const factLines = /^- /m.test(facts) ? facts.split("\n").filter((l) => /^- /.test(l)).map((l) => l.slice(2).trim()) : facts ? [facts] : [];
  const verifyAt = urls(facts);
  const overall = confidence(facts);
  const factsThatChange = factLines.filter((l) => !/^none\b/i.test(l) && !/^Verify at /i.test(l)).map((l) => ({
    fact: l.replace(/\s+/g, " ").slice(0, 600), lastChecked: LAST_CHECKED,
    confidence: /(VERIFIED|SNIPPET|SECONDARY|UNVERIFIED)/.test(l) ? confidence(l) : overall, staleAfterDays: 90, verifyAt }));
  const srcText = t("Sources");
  const note = /\(([^)]*)\)\s*$/m.exec(srcText)?.[1] ?? "";
  const sources = [{ text: srcText.replace(/\s+/g, " ").slice(0, 600), urls: [...new Set([...urls(srcText), ...verifyAt])], licence: note.slice(0, 200),
    usage: /link only/i.test(srcText) ? "link-only" : "paraphrase-with-attribution" }];
  const text = t("Body");
  entries.push({ id, version: 1, category: CATEGORIES[cat], title: t("Title").slice(0, 120), body: text, tags: tags.get(id) ?? [], keywords: [],
    factsThatChange, hardRules: hardRules(text), sources, lastReviewed: LAST_CHECKED });
}
const lib = { library: "foundational", version: 1, builtFrom: src, lastReviewed: LAST_CHECKED, entries };
fs.writeFileSync(out, JSON.stringify(lib, null, 1) + "\n");
// The schema migration ships this exact library (a generated module, so the release build needs no JSON loader).
fs.writeFileSync("src/fleet/postgres/knowledge-library-v1.ts", `/* Generated by scripts/knowledge-library-build.mjs from ${src} — do not edit by hand. */\n`
  + `export const KNOWLEDGE_LIBRARY_V1 = ${JSON.stringify(lib)} as const;\n`);
console.log(`${entries.length} entries → ${out} (${entries.reduce((n, e) => n + e.hardRules.length, 0)} hard rules, ${entries.reduce((n, e) => n + e.factsThatChange.length, 0)} changeable facts)`);
