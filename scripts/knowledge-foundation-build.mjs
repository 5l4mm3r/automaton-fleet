#!/usr/bin/env node
/**
 * Build the business foundation (library categories `business-foundation` and `fleet-status`) from its one master source,
 * docs/knowledge/business-foundation-v1.md, into src/fleet/postgres/knowledge-foundation-v1.ts (seeded by schema v67).
 *
 *   node scripts/knowledge-foundation-build.mjs [source.md] [out.ts]
 *
 * Each "## <id>" section becomes one library entry: Title, Category, Tags, Related (cross-references, appended to the body),
 * Sources ("url | what | checked YYYY-MM-DD"), Facts ("fact | checked YYYY-MM-DD | confidence" — dated status, stale after
 * 14 days) and Body. The "Reading path" line fixes the order of a full read. Hard rules stay empty: this is guidance; law,
 * platform terms and Fleet rules live in the charter and the legal entries. Deterministic: the same source gives the same file.
 */
import fs from "node:fs";

const [src = "docs/knowledge/business-foundation-v1.md", out = "src/fleet/postgres/knowledge-foundation-v1.ts"] = process.argv.slice(2);
const md = fs.readFileSync(src, "utf8");
const VERSION = "business-foundation-v1";
const REVIEWED = "2026-10-12";
const CATEGORIES = new Set(["business-foundation", "fleet-status"]);
const fail = (m) => { console.error(`knowledge-foundation-build: ${m}`); process.exit(1); };

const pathLine = /Reading path \(in order\):([\s\S]*?)\n\n/.exec(md);
if (!pathLine) fail("no reading path");
const readingPath = pathLine[1].split(",").map((s) => s.trim()).filter(Boolean);

const entries = [];
for (const block of md.split(/^(?=## )/m).slice(1)) {
  const id = /^## ([a-z0-9]+(?:-[a-z0-9]+)*)\s*\n/.exec(block)?.[1];
  if (!id) fail(`bad heading: ${block.slice(0, 40)}`);
  const field = (name) => new RegExp(`^${name}: (.+)$`, "m").exec(block)?.[1]?.trim();
  const list = (name) => {
    const m = new RegExp(`^${name}:\\n((?:- .+\\n?)+)`, "m").exec(block);
    return m ? m[1].trim().split("\n").map((l) => l.replace(/^- /, "").trim()) : [];
  };
  const bodyAt = block.indexOf("\nBody:\n");
  if (bodyAt < 0) fail(`${id}: no Body`);
  const title = field("Title"), category = field("Category");
  if (!title || title.length > 120) fail(`${id}: title`);
  if (!CATEGORIES.has(category)) fail(`${id}: category ${category}`);
  const related = (field("Related") ?? "").split(",").map((s) => s.trim()).filter(Boolean);
  let body = block.slice(bodyAt + 7).replace(/\n---\s*$/m, "").trim();
  if (related.length) body += `\n\nRelated: ${related.join(", ")}`;
  if (body.length < 10 || body.length > 6000) fail(`${id}: body length ${body.length}`);
  const sources = list("Sources").map((l) => {
    const [url, what, checked] = l.split(" | ").map((s) => s.trim());
    if (!/^https:\/\//.test(url ?? "") || !/^checked \d{4}-\d{2}-\d{2}$/.test(checked ?? "")) fail(`${id}: source ${l}`);
    return { text: `- ${url} (${what}; ${checked})`, urls: [url], licence: "official or primary page: facts paraphrased, link only", usage: "link-only" };
  });
  const facts = list("Facts").map((l) => {
    const [fact, checked, confidence] = l.split(" | ").map((s) => s.trim());
    const d = /^checked (\d{4}-\d{2}-\d{2})$/.exec(checked ?? "")?.[1];
    if (!fact || !d || !["verified", "unverified"].includes(confidence)) fail(`${id}: fact ${l}`);
    return { fact, lastChecked: d, confidence: confidence === "verified" ? "verified-official" : "unverified", staleAfterDays: 14, verifyAt: [] };
  });
  entries.push({ id, version: 1, category, title, body, tags: (field("Tags") ?? "").split(",").map((s) => s.trim()).filter(Boolean),
    keywords: [], factsThatChange: facts, hardRules: [], sources, lastReviewed: REVIEWED, recommendations: [] });
}
const ids = new Set(entries.map((e) => e.id));
if (ids.size !== entries.length) fail("duplicate ids");
for (const p of readingPath) if (!ids.has(p)) fail(`reading path names an unknown entry: ${p}`);
for (const e of entries) if (!readingPath.includes(e.id)) fail(`entry not on the reading path: ${e.id}`);

const lib = { library: "business-foundation", version: VERSION, builtFrom: src, lastReviewed: REVIEWED, readingPath, entries };
fs.writeFileSync(out, `/* Generated by scripts/knowledge-foundation-build.mjs from ${src} — do not edit by hand. */\n`
  + `export const KNOWLEDGE_FOUNDATION_V1 = ${JSON.stringify(lib)} as const;\n`);
console.log(JSON.stringify({ out, version: VERSION, entries: entries.length, readingPath: readingPath.length,
  chars: entries.reduce((n, e) => n + e.body.length, 0), maxBody: Math.max(...entries.map((e) => e.body.length)) }));
